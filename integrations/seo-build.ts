import type { AstroIntegration } from 'astro';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { site, isSet } from '../src/config/site.ts';

async function htmlFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(p)));
    else if (entry.name === 'index.html') out.push(p);
  }
  return out;
}

const origin = (url: string) => {
  if (!isSet(url)) return null;
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
};

/**
 * Post-build SEO tasks:
 * - sitemap.xml built from the real output (drafts are never built, so never listed),
 *   with <lastmod> read from each page's data-updated attribute; noindex pages skipped.
 * - _headers for Cloudflare Pages with a CSP derived from src/config/site.ts.
 */
export function seoBuild(): AstroIntegration {
  return {
    name: 'worksai-seo-build',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const files = await htmlFiles(root);
        const entries: { loc: string; lastmod: string }[] = [];
        for (const file of files) {
          const html = await readFile(file, 'utf8');
          if (/<meta name="robots" content="[^"]*noindex/.test(html)) continue;
          const rel = relative(root, file).split(sep).join('/').replace(/index\.html$/, '');
          if (rel.startsWith('404')) continue;
          const lastmod = html.match(/<html[^>]*data-updated="([\d-]+)"/)?.[1] ?? site.defaultUpdated;
          entries.push({ loc: `${site.url}/${rel}`, lastmod });
        }
        entries.sort((a, b) => a.loc.split('/').length - b.loc.split('/').length || a.loc.localeCompare(b.loc));
        const xml =
          `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
          entries.map((e) => `  <url><loc>${e.loc}</loc><lastmod>${e.lastmod}</lastmod></url>`).join('\n') +
          `\n</urlset>\n`;
        await writeFile(join(root, 'sitemap.xml'), xml);
        logger.info(`sitemap.xml written with ${entries.length} URLs`);

        // ----- _headers -----
        const ga = isSet(site.ga4Id);
        const gaScript = ga ? ' https://www.googletagmanager.com' : '';
        const gaConnect = ga ? ' https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com' : '';
        const gaImg = ga ? ' https://*.google-analytics.com https://www.googletagmanager.com' : '';
        const form = origin(site.formEndpoint);
        const booking = origin(site.bookingUrl);
        const csp = [
          "default-src 'self'",
          `script-src 'self'${gaScript}`,
          "style-src 'self' 'unsafe-inline'",
          `img-src 'self' data:${gaImg}`,
          "font-src 'self'",
          `connect-src 'self'${gaConnect}${form ? ' ' + form : ''}`,
          `frame-src ${booking ?? "'none'"}`,
          `form-action 'self'${form ? ' ' + form : ''} https://wa.me`,
          "base-uri 'self'",
          "object-src 'none'",
          "frame-ancestors 'none'",
          'upgrade-insecure-requests',
        ].join('; ');
        const headers = `# Generated by integrations/seo-build.ts on build. Edit that file, not this one.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/og/*
  Cache-Control: public, max-age=86400

/*.xml
  Cache-Control: public, max-age=3600
`;
        await writeFile(join(root, '_headers'), headers);
        logger.info('_headers written');
      },
    },
  };
}
