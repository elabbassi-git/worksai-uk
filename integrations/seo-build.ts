import type { AstroIntegration } from 'astro';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { site, isSet } from '../src/config/site.ts';

async function htmlFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(p)));
    else if (entry.name === 'index.html') out.push(p);
  }
  return out;
}

const origin = (url: string) => {
  if (!isSet(url)) return null;
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
};

/**
 * Post-build SEO tasks:
 * - sitemap.xml built from the real output (drafts are never built, so never listed),
 *   with <lastmod> read from each page's data-updated attribute; noindex pages skipped.
 * - _headers for Cloudflare Pages with a CSP derived from src/config/site.ts.
 * - .htaccess with the same rules for Apache/LiteSpeed hosting (Spaceship cPanel).
 */
export function seoBuild(): AstroIntegration {
  return {
    name: 'worksai-seo-build',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const files = await htmlFiles(root);
        const entries: { loc: string; lastmod: string }[] = [];
        for (const file of files) {
          const html = await readFile(file, 'utf8');
          if (/<meta name="robots" content="[^"]*noindex/.test(html)) continue;
          const rel = relative(root, file).split(sep).join('/').replace(/index\.html$/, '');
          if (rel.startsWith('404')) continue;
          const lastmod = html.match(/<html[^>]*data-updated="([\d-]+)"/)?.[1] ?? site.defaultUpdated;
          entries.push({ loc: `${site.url}/${rel}`, lastmod });
        }
        entries.sort((a, b) => a.loc.split('/').length - b.loc.split('/').length || a.loc.localeCompare(b.loc));
        const xml =
          `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
          entries.map((e) => `  <url><loc>${e.loc}</loc><lastmod>${e.lastmod}</lastmod></url>`).join('\n') +
          `\n</urlset>\n`;
        await writeFile(join(root, 'sitemap.xml'), xml);
        logger.info(`sitemap.xml written with ${entries.length} URLs`);

        // ----- _headers -----
        const ga = isSet(site.ga4Id);
        const gaScript = ga ? ' https://www.googletagmanager.com' : '';
        const gaConnect = ga ? ' https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com' : '';
        const gaImg = ga ? ' https://*.google-analytics.com https://www.googletagmanager.com' : '';
        const form = origin(site.formEndpoint);
        const booking = origin(site.bookingUrl);
        const csp = [
          "default-src 'self'",
          `script-src 'self'${gaScript}`,
          "style-src 'self' 'unsafe-inline'",
          `img-src 'self' data:${gaImg}`,
          "font-src 'self'",
          `connect-src 'self'${gaConnect}${form ? ' ' + form : ''}`,
          `frame-src ${booking ?? "'none'"}`,
          `form-action 'self'${form ? ' ' + form : ''} https://wa.me`,
          "base-uri 'self'",
          "object-src 'none'",
          "frame-ancestors 'none'",
          'upgrade-insecure-requests',
        ].join('; ');
        const headers = `# Generated by integrations/seo-build.ts on build. Edit that file, not this one.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/og/*
  Cache-Control: public, max-age=86400

/*.xml
  Cache-Control: public, max-age=3600
`;
        await writeFile(join(root, '_headers'), headers);
        logger.info('_headers written');

        // ----- .htaccess (Apache / LiteSpeed hosting, e.g. Spaceship cPanel) -----
        // Same redirects, security headers and caching as _redirects/_headers above.
        const host = new URL(site.url).host;
        const rules: string[] = [];
        const redirects = await readFile(join(root, '_redirects'), 'utf8').catch(() => '');
        for (const raw of redirects.split('\n')) {
          const line = raw.trim();
          if (!line || line.startsWith('#')) continue;
          const [from, to, code = '301'] = line.split(/\s+/);
          if (!from?.startsWith('/') || !to) continue;
          if (from === '/index.html') continue; // handled with THE_REQUEST below (mod_dir subrequests)
          const esc = (x: string) => x.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
          let pattern: string;
          let target = to;
          if (from.endsWith('/*')) {
            pattern = `^${esc(from.slice(1, -2))}/(.*)$`;
            target = to.replace(':splat', '$1');
          } else {
            pattern = `^${esc(from.slice(1).replace(/\/$/, ''))}/?$`;
          }
          rules.push(`RewriteRule ${pattern} ${target} [R=${code},L]`);
        }
        const header = (k: string, v: string) => `  Header always set ${k} "${v.replace(/"/g, '\\"')}"`;
        const htaccess = `# Generated by integrations/seo-build.ts on build. Edit that file, not this one.
Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8
AddCharset utf-8 .txt .xml .html .css .js .json .svg
AddType application/rss+xml .rss

<FilesMatch "^(_headers|_redirects)$">
  Require all denied
</FilesMatch>

RewriteEngine On

# One canonical origin: https://${host} (ACME challenges left alone for AutoSSL)
RewriteCond %{REQUEST_URI} !^/\\.well-known/
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, '\\.')}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]

# Directories always end with a slash (Astro trailingSlash: 'always')
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^(.+[^/])$ https://${host}/$1/ [R=301,L]

RewriteCond %{THE_REQUEST} \\s/index\\.html[\\s?]
RewriteRule ^index\\.html$ / [R=301,L]

${rules.join('\n')}

<IfModule mod_headers.c>
${header('Content-Security-Policy', csp)}
${header('Strict-Transport-Security', 'max-age=31536000; includeSubDomains')}
${header('X-Content-Type-Options', 'nosniff')}
${header('X-Frame-Options', 'DENY')}
${header('Referrer-Policy', 'strict-origin-when-cross-origin')}
${header('Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), interest-cohort=()')}
${header('Cross-Origin-Opener-Policy', 'same-origin')}
  Header unset X-Powered-By
  <FilesMatch "\\.(html)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\\.(xml|txt)$">
    Header set Cache-Control "public, max-age=3600"
  </FilesMatch>
</IfModule>
`;
        await writeFile(join(root, '.htaccess'), htaccess);
        const cacheFor = (seconds: number, immutable = false) =>
          `# Generated by integrations/seo-build.ts\n<IfModule mod_headers.c>\n  Header set Cache-Control "public, max-age=${seconds}${immutable ? ', immutable' : ''}"\n</IfModule>\n`;
        for (const [dirName, body] of [
          ['_astro', cacheFor(31536000, true)],
          ['fonts', cacheFor(31536000, true)],
          ['og', cacheFor(86400)],
        ] as const) {
          await writeFile(join(root, dirName, '.htaccess'), body).catch(() => {});
        }
        logger.info('.htaccess written');
      },
    },
  };
}
